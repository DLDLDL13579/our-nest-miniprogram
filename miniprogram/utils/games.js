/** 按 id 取玩法元数据；取不到返回 null（调用方必须显式处理，不许静默兜底成别的玩法） */
function gameOf(id) {
  for (let i = 0; i < GAMES.length; i++) if (GAMES[i].id === id) return GAMES[i]
  return null
}

/** 全部玩法 id —— 服务端校验用 */
function gameIds() {
  return GAMES.map(g => g.id)
}

/** 某个分类下的玩法 */
function gamesInCat(cat) {
  return GAMES.filter(g => g.cat === cat)
}

/** 玩法名（找不到时返回空串，不要回退成"随便"） */
function gameName(id) {
  const g = gameOf(id)
  return g ? g.name : ''
}

module.exports = { CATS, GAMES, gameOf, gameIds, gamesInCat, gameName }
