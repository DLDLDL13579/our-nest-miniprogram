/**
 * games.js —— 游戏注册表（全工程唯一事实源）
 *
 * ============ 为什么要有这个文件 ============
 *
 * 改造前「有哪些玩法」这件事散在 **5 个地方**，各写各的：
 *   ① miniprogram/pages/game/game.js 的 MODES（大厅介绍）
 *   ② miniprogram/pages/game/room/room.js 的 GAMES（房内换玩法）
 *   ③ cloudfunctions/room/index.js 的 `['dice','liar','wheel'].indexOf(...)`（校验）
 *   ④ room.wxml 里 `wx:if="{{room.game === 'liar'}}"` 这类模板分支
 *   ⑤ room.wxss 里每个玩法各自的样式块
 *
 * 后果和 AGENTS.md 记过的「派生字段有 7 个出口」是同一类：
 * **加一个玩法时漏改一处，不报错，只是那个玩法永远用不上/显示不出来**。
 *
 * 所以收敛成这里：**加游戏 = 往数组里加一项 + 写它的规则模块**，
 * 大厅、房内切换、服务端校验、图标准备全部自动跟上。
 *
 * ============ 收不收一个玩法的判据（用户 2026-10-27 明确）============
 *
 *    「现场能玩的，完全可以抛开手机的游戏不用写。」
 *
 * 换句话说：**手机必须提供现实中难以替代的价值**，否则这个玩法就是多余的。
 * 具体看它满足哪一条：
 *
 *   ① 需要秘密信息 —— 别人不能看见。骰子点数、卧底身份。
 *      现实要靠"捂住/抽纸条"，手机天然做到。
 *   ② 需要真随机且可验证 —— 骰子、转盘、抽题。现实要带道具。
 *   ③ 需要大量内容库 —— 题库、词库。现实要打印一沓卡片。
 *   ④ 需要仲裁顺序/计时 —— 抢答、回合。
 *   ⑤ 需要跨轮持久记录 —— 记分。
 *
 * ⚠️ 只满足 ⑤（记分）通常**不够**：《我有你没有》就是被这条否掉的 ——
 *    现实里举 10 根手指就能记，手机反而是多一层操作。
 *    真要做记分类玩法，必须同时满足 ①~④ 里的至少一条。
 *
 * ============ 云端要一份拷贝 ============
 * 云函数独立打包、不能跨目录 require，所以 cloudfunctions/room/games.js
 * 是本文件的拷贝，由 scripts/sync-derive.sh 自动同步（改完跑一次即可）。
 * 本文件必须是**纯数据 + 纯函数**，不能碰 wx.* / 不能 require 小程序专有模块，
 * 否则云端 require 时会炸。
 */

