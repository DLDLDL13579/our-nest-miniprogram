/** 按 key 取一副词库；取不到回退到第一副（不让房间卡在"没有词可抽"） */
function deckOf(k) {
  for (let i = 0; i < DECKS.length; i++) if (DECKS[i].k === k) return DECKS[i]
  return DECKS[0]
}

/**
 * 抽一对词。
 *
 * @param {string} k     词库 key
 * @param {function} rnd 可注入的随机源（测试用，默认 Math.random）
 * @returns {{civilian: string, spy: string, deck: string}}
 */
function pickPair(k, rnd) {
  const d = deckOf(k)
  const r = rnd || Math.random
  const p = d.pairs[Math.floor(r() * d.pairs.length)] || d.pairs[0]
  return { civilian: p[0], spy: p[1], deck: d.k }
}

/** 所有词库（给界面渲染选择用，只暴露名字和说明，不暴露具体词） */
function meta() {
  return DECKS.map(d => ({ k: d.k, name: d.name, desc: d.desc, count: d.pairs.length }))
}

module.exports = { DECKS, deckOf, pickPair, meta }
