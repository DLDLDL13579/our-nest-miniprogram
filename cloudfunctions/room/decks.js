/**
 * 酒桌题卡库 —— 真心话 / 大冒险
 *
 * ============ 为什么按「场合」分，而不是按「尺度」分 ============
 *
 * 尺度是**把关者视角**（我替你定能玩多开），场合是**玩家视角**（我们今晚是什么局）。
 * 同一批人，在家喝、在同事聚餐、在长辈面前，需要的是**不同的题库**，
 * 而不是同一套题调辣度 —— 后者会让每个场合都"差一点"。
 *
 * 所以每个场合是一副**独立的牌**，各自完整、各自得体。
 *
 * ============ 收录标准（比"好不好玩"更重要） ============
 *
 * ★ 一条题要能通过这三问才收：
 *   ① **不需要道具**：桌上只有酒和手机。要笔、要牌、要跑出去的，不要。
 *   ② **不需要演技/才艺**：让不会唱歌的人唱歌，只会让全场尴尬。
 *   ③ **指向具体、可回答**： "你最难忘的事是什么" 这种太泛，会冷场；
 *      "你手机相册最近一张截图是什么" 这种一句话就能答。
 *
 * ★ 刻意不收的几类（都是"看起来热闹、实际毁气氛"）：
 *   · 涉及在场某人隐私的（"你觉得在座谁最丑"）—— 会真的伤人
 *   · 需要暴露真实秘密的（"说出你银行卡密码"）—— 不喝就是不喝，撬不动的
 *   · 性暗示直白的 —— 同事局直接尬住
 *   · 让人下不来台的 —— 玩游戏的目的是都开心，不是淘汰谁
 *
 * ============ 为什么内置在前端 ============
 * 离线可用、不依赖网络、不消耗云函数调用次数。
 * 抽题在**服务端**做（与转盘同理）—— 前端抽的话，"重摇到满意"就穿帮了。
 */

