/* 出场顺序 = 界面上的顺序。朋友聚会排第一（最常用） */
const DECKS = [FRIENDS, COUPLE, FAMILY, COLLEAGUE]

/** 按 key 取一副牌；找不到就回退到朋友聚会（保证永远有题可抽） */
function deckOf(key) {
  return DECKS.filter(d => d.k === key)[0] || FRIENDS
}

/**
 * 题目去重/去空白的自检数据（给断言用）。
 * 收录标准里最容易违反的一条是"两副牌里出现同一道题"——
 * 那会让换场合的人觉得"怎么还是这些"。
 *
 * ★ 2026-11-03：这条**曾经只是注释**（说"给断言用"而断言不存在）——
 *   现在真的有了：test-mock.js 的「题卡库不许有重复」。
 *   注释里写清出处，是为了让下一个人能一眼确认它有没有兑现。
 */
function allTexts() {
  const out = []
  DECKS.forEach(d => {
    d.truth.forEach(t => out.push({ deck: d.k, type: 'truth', text: t }))
    d.dare.forEach(t => out.push({ deck: d.k, type: 'dare', text: t }))
  })
  return out
}

module.exports = { DECKS, deckOf, allTexts }
