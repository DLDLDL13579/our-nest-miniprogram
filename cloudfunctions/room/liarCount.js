/**
 * liarCount.js —— 大话骰「实际有几个」的统计
 *
 * ============ 为什么要单独抽出来 ============
 *
 * 这是大话骰**唯一的判定核心**：开骰时数全场有多少颗能满足叫的点数。
 * 而它有一条反直觉的规则：**1 点恒为万能**（可以当任何点数），
 * 除非叫的就是 1 —— 那时 1 只能算 1。
 *
 * 原逻辑内联在 `open` 分支里，而骰子是**随机发的**，
 * 所以从来没法单测 —— 测试只能验"actual >= need 这个判定对不对"，
 * 验不了"1 有没有被算进去"。
 *
 * 抽出来之后，喂数据就能断言。
 */

/**
 * @param {Array} players  玩家列表（每人有 dice 数组）
 * @param {number} face    叫的点数（1~6）
 * @param {boolean} [zhai] **斋**：1 点不再万能，只算 1
 * @returns {number}       全场能满足这个叫法的骰子数
 *
 * ★ 斋（2026-10-30 用户实测后补）：广东玩法的核心分支。
 *   不斋时 1 是万能「百搭」，斋时 1 就只是 1 —— 这直接决定开骰判谁喝。
 *   之前只实现了不斋（1 恒万能），所以叫「3个4斋」时会把 1 也数进去，
 *   等于**在帮叫的人作弊**，开骰结果必错。
 */
function countActual(players, face, zhai) {
  let n = 0
  ;(players || []).forEach(p => {
    const dice = p.dice || []
    let cnt = 0
    dice.forEach(d => {
      if (d === face) cnt++
      /* 1 是万能 —— 但两种情况不算：
         · 叫的就是 1（1 只代表自己）
         · **斋**（1 不当任何别的点数） */
      else if (d === 1 && face !== 1 && !zhai) cnt++
    })
    /*
     * ★★★ 2026-11-02 按调研补全「围骰 / 全围」的分级。
     *
     * 原来的实现只做了「加一」——**把所有五个相同都当成围骰**。
     * 而真实规则分两档（维基百科「大话骰」条目写得很清楚）：
     *
     *   「围骰」骰盅内含 1 全为一个数 → **加一**
     *     （非斋的五个 2 可以当六个 2 用）
     *   「全围」骰盅全都为一个数 → **加二**
     *     （斋五个 2 可以当七个 2 用）
     *
     * 区别就是：**这一盅够五个是靠 1 凑的，还是本来就全是那个数**。
     *   [6,6,6,6,6] 叫 6 → 全围，5 + 2 = **7 个**
     *   [1,1,1,1,1] 叫 6（不斋）→ 围骰，5 + 1 = **6 个**
     *   [1,1,1,1,1] 叫 1 → 就是 5 个 1，不算围骰（1 只代表自己）
     *
     * 少做「全围 +2」的后果：摇出五个 6 的人少算一个 ——
     * 而那是 1/1296 的运气，少给一分就是在砍酒桌上最值得喊出来的那一刻。
     */
    if (dice.length === 5 && dice.every(d => d === dice[0])) {
      const v = dice[0]
      if (v === face) {
        /* 全围：五颗都是叫的点数（叫 1 时不算奖励 —— 那是 1 的本分） */
        if (face !== 1) cnt += 2
      } else if (v === 1 && face !== 1 && !zhai) {
        /* 围骰：靠万能 1 撑起来的五个 */
        cnt += 1
      }
    }
    n += cnt
  })
  return n
}

module.exports = { countActual: countActual }
