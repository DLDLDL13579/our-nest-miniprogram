/**
 * liarCount.js —— 大话骰「实际有几个」的统计
 *
 * ============ 为什么要单独抽出来 ============
 *
 * 这是大话骰**唯一的判定核心**：开骰时数全场有多少颗能满足叫的点数。
 * 而它有一条反直觉的规则：**1 点恒为万能**（可以当任何点数），
 * 除非叫的就是 1 —— 那时 1 只能算 1。
 *
 * 原逻辑内联在 `open` 分支里，而骰子是**随机发的**，
 * 所以从来没法单测 —— 测试只能验"actual >= need 这个判定对不对"，
 * 验不了"1 有没有被算进去"。
 *
 * 抽出来之后，喂数据就能断言。
 */

/**
 * @param {Array} players  玩家列表（每人有 dice 数组）
 * @param {number} face    叫的点数（1~6）
 * @param {boolean} [zhai] **斋**：1 点不再万能，只算 1
 * @returns {number}       全场能满足这个叫法的骰子数
 *
 * ★ 斋（2026-10-30 用户实测后补）：广东玩法的核心分支。
 *   不斋时 1 是万能「百搭」，斋时 1 就只是 1 —— 这直接决定开骰判谁喝。
 *   之前只实现了不斋（1 恒万能），所以叫「3个4斋」时会把 1 也数进去，
 *   等于**在帮叫的人作弊**，开骰结果必错。
 */
function countActual(players, face, zhai) {
  let n = 0
  ;(players || []).forEach(p => {
    const dice = p.dice || []
    let cnt = 0
    dice.forEach(d => {
      if (d === face) cnt++
      /* 1 是万能 —— 但两种情况不算：
         · 叫的就是 1（1 只代表自己）
         · **斋**（1 不当任何别的点数） */
      else if (d === 1 && face !== 1 && !zhai) cnt++
    })
    /*
     * ★ 围骰加一（2026-10-30）：一盅 5 颗**完全相同**时，那个点数算 6 个。
     *
     * 调研里这条被归在"常用规则"，酒桌上很认 —— 摇出五个一样的概率是
     * 1/1296，值得给这份运气一点回报。
     *
     * 两种成立情形：
     *   · 5 颗全等于叫的点数（如叫 4、盅里 5 个 4）
     *   · 5 颗全是 1，且**不斋**（1 万能，等于什么点数都成立）
     */
    if (dice.length === 5 && dice.every(d => d === dice[0])) {
      const v = dice[0]
      if (v === face || (v === 1 && face !== 1 && !zhai)) cnt++
    }
    n += cnt
  })
  return n
}

module.exports = { countActual: countActual }
